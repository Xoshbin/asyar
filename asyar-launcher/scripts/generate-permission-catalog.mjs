#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const source = resolve(root, 'src-tauri/src/permissions.rs');

const text = readFileSync(source, 'utf8');
const fnMatch = text.match(
  /fn get_required_permission\(call_type: &str\) -> Option<&'static str> \{[\s\S]*?\n\}/,
);
if (!fnMatch) {
  throw new Error('could not find get_required_permission in permissions.rs');
}

const permissionRegex = /=>\s*Some\("([^"]+)"\)/g;
const harvested = new Set();
for (const m of fnMatch[0].matchAll(permissionRegex)) {
  harvested.add(m[1]);
}

const sorted = [...harvested].sort();
const out = `// AUTO-GENERATED by scripts/generate-permission-catalog.mjs — do not edit.
// Run \`pnpm gen:permission-catalog\` after changing
// permissions.rs::get_required_permission.

// Every permission string that Rust's get_required_permission can require —
// i.e. gates at least one asyar:api:* call. Not the full set of manifest-
// declarable permissions (see asyar-sdk/cli/lib/manifest.ts VALID_PERMISSIONS
// for that); some permissions are declarative-only and never appear here.
export const GATED_PERMISSIONS = ${JSON.stringify(sorted, null, 2)} as const;
`;

const outPath = resolve(root, 'src/services/extension/gatedPermissions.ts');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(`wrote ${outPath} with ${sorted.length} permissions`);
