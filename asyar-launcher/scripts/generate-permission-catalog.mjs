#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const launcherRoot = resolve(__dirname, '..');
const repoRoot = resolve(launcherRoot, '..');

const source = resolve(launcherRoot, 'src-tauri/src/permissions.rs');

const text = readFileSync(source, 'utf8');
const fnMatch = text.match(
  /fn get_required_permission\(call_type: &str\) -> Option<&'static str> \{[\s\S]*?\n\}/,
);
if (!fnMatch) {
  throw new Error('could not find get_required_permission in permissions.rs');
}

const permissionRegex = /=>\s*Some\("([^"]+)"\)/g;
const harvested = new Set();
for (const m of fnMatch[0].matchAll(permissionRegex)) {
  harvested.add(m[1]);
}

const sorted = [...harvested].sort();
const arrayLiteral = JSON.stringify(sorted, null, 2);

// The gated-permission list has two independent consumers that can't share one
// file: the launcher app, and the SEPARATELY-PUBLISHED `asyar` SDK CLI (which
// validates extension manifests and can't import the launcher's copy at publish
// time). One generator writes both copies from the single source
// (permissions.rs) so they can never drift and nobody can regenerate one and
// forget the other.
const targets = [
  {
    path: resolve(launcherRoot, 'src/services/extension/gatedPermissions.ts'),
    header: `// AUTO-GENERATED by scripts/generate-permission-catalog.mjs — do not edit.
// Writes this file AND asyar-sdk/cli/lib/gatedPermissions.ts together; run
// \`pnpm gen:permission-catalog\` after changing
// permissions.rs::get_required_permission.

// Every permission string that Rust's get_required_permission can require —
// i.e. gates at least one asyar:api:* call. Not the full set of manifest-
// declarable permissions (see asyar-sdk/cli/lib/manifest.ts VALID_PERMISSIONS
// for that); some permissions are declarative-only and never appear here.`,
  },
  {
    path: resolve(repoRoot, 'asyar-sdk/cli/lib/gatedPermissions.ts'),
    header: `// AUTO-GENERATED by asyar-launcher/scripts/generate-permission-catalog.mjs — do not edit.
// Written together with asyar-launcher's copy by the same generator; run
// \`pnpm gen:permission-catalog\` (from asyar-launcher) after changing
// asyar-launcher's permissions.rs::get_required_permission.

// Every permission string the launcher's Rust permission gate can require.
// Not the full set of manifest-declarable permissions — see this package's
// VALID_PERMISSIONS in lib/manifest.ts for that (deliberately broader:
// includes declarative-only permissions this gate never checks).`,
  },
];

for (const { path, header } of targets) {
  const out = `${header}
export const GATED_PERMISSIONS = ${arrayLiteral} as const;
`;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, out);
  console.log(`wrote ${path} with ${sorted.length} permissions`);
}
