#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const source = resolve(root, '../asyar-launcher/src-tauri/src/permissions.rs');

const text = readFileSync(source, 'utf8');
const fnMatch = text.match(
  /fn get_required_permission\(call_type: &str\) -> Option<&'static str> \{[\s\S]*?\n\}/,
);
if (!fnMatch) {
  throw new Error('could not find get_required_permission in permissions.rs');
}

const permissionRegex = /=>\s*Some\("([^"]+)"\)/g;
const harvested = new Set();
for (const m of fnMatch[0].matchAll(permissionRegex)) {
  harvested.add(m[1]);
}

const sorted = [...harvested].sort();
const out = `// AUTO-GENERATED by scripts/generate-gated-permissions.mjs — do not edit.
// Run \`npm run gen:gated-permissions\` after changing asyar-launcher's
// permissions.rs::get_required_permission.

// Every permission string the launcher's Rust permission gate can require.
// Not the full set of manifest-declarable permissions — see this package's
// VALID_PERMISSIONS in lib/manifest.ts for that (deliberately broader:
// includes declarative-only permissions this gate never checks).
export const GATED_PERMISSIONS = ${JSON.stringify(sorted, null, 2)} as const;
`;

const outPath = resolve(root, 'cli/lib/gatedPermissions.ts');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(`wrote ${outPath} with ${sorted.length} permissions`);
