#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const source = resolve(root, '../asyar-launcher/src-tauri/src/runtimes/catalog.fallback.json');

const catalog = JSON.parse(readFileSync(source, 'utf8'));
const sorted = Object.keys(catalog.runtimes).sort();

const out = `// AUTO-GENERATED by scripts/generate-known-runtimes.mjs — do not edit.
// Run \`npm run gen:known-runtimes\` after changing asyar-launcher's
// runtimes/catalog.fallback.json.

// Mirrors asyar-launcher's runtimes::catalog::known_names() (Rust), which
// reads this same catalog.fallback.json — that file is the real source of
// truth for both sides.
export const KNOWN_RUNTIMES = ${JSON.stringify(sorted, null, 2)} as const;
`;

const outPath = resolve(root, 'cli/lib/knownRuntimes.ts');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(`wrote ${outPath} with ${sorted.length} runtimes`);
